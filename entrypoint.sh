# Аварийное завершение скрипта при возврате ненулевого кода любой из команд (POSIX стандарт).
# Предотвращает запуск веб-сервера при сбое инициализации инфраструктуры
set -e

echo "[Entrypoint] Накатываем миграции НАПРЯМУЮ в PostgreSQL (Порт 5432), минуя транзакционный PgBouncer..."
# Временное переопределение DB_HOST вместо pgbouncer на postgresql
# Миграции (DDL) требуют постоянного сессионного соединения и несовместимы с Transaction Pooling в PgBouncer.
DB_HOST=$PGBOUNCER_BACKEND_HOST python manage.py migrate --database=default --noinput

echo "[Entrypoint] Запуск кастомной команды прогрева каталога товаров..."
# Команда отправляет таску в брокер сообщений (Redis-инстас3, 6381)
# и мгновенно завершается, не блокируя основной поток выполнения контейнера.
python manage.py warmup_catalog

echo "[Entrypoint] Инфраструктура прогрета. Передаем управление процессу веб-сервера!"
# Полностью стирает текущий скрипт entrypoint.sh из оперативной памяти 
# контейнера и запускает на его месте финальную команду (веб-сервер)
exec "$@"